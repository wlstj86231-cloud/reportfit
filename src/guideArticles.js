export const guideArticles = [
  ...coreGuideArticles,
  ...additionalGuideSeeds.map(createOperationalGuide)
];

export function articleText(article) {
  return [
    article.title,
    article.description,
    article.summary,
    article.experienceNote?.title,
    ...(article.experienceNote?.paragraphs || []),
    ...article.sections.flatMap((section) => [
      section.heading,
      ...section.paragraphs
    ]),
    ...article.faq.flatMap((item) => [item.q, item.a])
  ].join("\n\n");
}
